#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	unsigned char	*b;
	size_t			i;

	b = (unsigned char *)s;
	i = 0;
	while (i < n)
	{
		if (*b == (unsigned char)c)
			return (b);
		i++;
		b++;
	}
	return (NULL);
}
